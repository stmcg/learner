#' Simulated data set: Multiple sources with different noise levels
#'
#' Simulated matrices for one target population and two source populations.
#' The sources share the target's latent row and column spaces, but source A
#' is observed more precisely than source B. This data set illustrates fitting
#' LEARNER and D-LEARNER with multiple sources.
#'
#' @docType data
#' @format A list with four components. All matrices have 100 rows and 50 columns,
#'   with corresponding rows and columns aligned across populations.
#' \describe{
#'   \item{\code{Y_source}}{A named list of observed source matrices, \code{A}
#'     and \code{B}, suitable for the \code{Y_source} argument.}
#'   \item{\code{Y_target}}{The observed target matrix.}
#'   \item{\code{Theta_source}}{A named list of the true rank-3 source matrices,
#'     \code{A} and \code{B}. The two true matrices are identical.}
#'   \item{\code{Theta_target}}{The true rank-3 target matrix.}
#' }
#' @details
#' The source signal is obtained by reversing the three nonzero singular values
#' of the target signal while keeping its singular vectors. Each observed matrix
#' is generated by adding independent, mean-zero normal noise to its own signal.
#' Noise is independent across entries and populations, with variances 0.10 for
#' the target, 0.01 for source A, and 0.50 for source B. Thus, source A has less
#' noise than the target and source B has more. Source B is not generated from
#' the observed source A matrix.
#'
#' The true signal matrices are included for illustration and estimation-error
#' calculations; they are not inputs to the fitting functions. These simulated
#' data are a usage example, not a reproduction of the paper's simulation study.
#'
#' @examples
#' data(dat_multisource)
#' fit <- dlearner(
#'   Y_source = dat_multisource$Y_source,
#'   Y_target = dat_multisource$Y_target,
#'   r = 3, source_weights = c(0.7, 0.3)
#' )
#' dim(fit$dlearner_estimate)
#' @seealso \code{\link{dat_highsim}}, \code{\link{dat_modsim}},
#'   \code{\link{learner}}, \code{\link{dlearner}}
#' @keywords datasets
"dat_multisource"
